  ('SERVICIOS_EDUCATIVOS.INSCRIPCION_CURSO.READ',   'Permiso de API NestJS SERVICIOS_EDUCATIVOS.INSCRIPCION_CURSO.READ',   'SERVICIOS_EDUCATIVOS', 'Activo'),
  ('SERVICIOS_EDUCATIVOS.INSCRIPCION_CURSO.UPDATE', 'Permiso de API NestJS SERVICIOS_EDUCATIVOS.INSCRIPCION_CURSO.UPDATE', 'SERVICIOS_EDUCATIVOS', 'Activo')
ON CONFLICT (codigo) DO UPDATE SET estado_registro = 'Activo';

-- Se concede a los mismos roles que ya administran las clases del curso: quien
-- puede crear una clase es quien matricula. Así no hace falta mantener una
-- segunda lista de roles que se desincronice de la primera.
INSERT INTO seguridad.rol_permiso (id_rol, id_permiso)
SELECT DISTINCT rol_clase.id_rol, nuevo.id_permiso
FROM seguridad.rol_permiso rol_clase
JOIN seguridad.permiso permiso_clase
  ON permiso_clase.id_permiso = rol_clase.id_permiso
 AND permiso_clase.codigo LIKE 'SERVICIOS_EDUCATIVOS.CLASE_CURSO.%'
JOIN seguridad.permiso nuevo
  ON nuevo.codigo = replace(permiso_clase.codigo, 'CLASE_CURSO', 'INSCRIPCION_CURSO')
ON CONFLICT DO NOTHING;
